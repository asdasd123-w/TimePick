// FurnitureSpec.ts —— 每件家具的「现实比例」缩放（单一数据源）
// ---------------------------------------------------------------------------
// 为什么要这张表：13 个 glb 都是按各自的建模习惯导出的，原始尺寸彼此不成比例 ——
// 书包 0.70×0.82×0.71（现实里约 0.30×0.45×0.20）、台灯高达 1.11（现实约 0.45）、
// 而床只有 0.69×0.43×0.99（现实单人床约 1.0×0.45×2.0）。
// 房间（house_three）在 Cocos 里放大 4.5 倍后约 3.31m 宽 × 4.00m 深（见 RoomSpec.ts），
// 按 1 单位 ≈ 1 米来折算，就能给每件家具一个"看着对"的缩放。
//
// 数值怎么定的：先离线解析每个 glb 的 POSITION 包围盒（脚本见工程外，结果见下表注释），
// 再按「该件家具在现实中的主要尺寸」反推缩放系数。大件（床/书柜/书桌/椅子）给到
// 接近现实的上限，小件（水杯/台灯/书包/书本）压到现实尺寸，避免"书包占半间房"。
//
//   bed        0.690×0.429×0.988  → ×1.55 = 1.07×0.67×1.53   单人床
//   desk       0.959×0.569×0.508  → ×1.25 = 1.20×0.71×0.64   书桌
//   chair      0.601×0.852×0.634  → ×1.10 = 0.66×0.94×0.70   椅子
//   cabinet   0.549×1.060×0.224  → ×1.30 = 0.71×1.38×0.29   书架（仍低于 1.57 的墙高）
//   computer   0.793×0.488×0.794  → ×0.85 = 0.67×0.41×0.67   显示器+键盘
//   record     0.796×0.624×0.792  → ×0.55 = 0.44×0.34×0.44   唱片机
//   schoolbag  0.700×0.824×0.707  → ×0.42 = 0.29×0.35×0.30   书包
//   tableLamp  0.803×1.109×0.799  → ×0.45 = 0.36×0.50×0.36   台灯
//   camera_my  1.001×0.278×0.975  → ×0.40 = 0.40×0.11×0.39   相机
//   cup        1.005×0.686×0.713  → ×0.25 = 0.25×0.17×0.18   水杯
//   diary      0.720×0.179×0.967  → ×0.50 = 0.36×0.09×0.48   日记本
//   greenbook  0.657×0.144×0.999  → ×0.50 = 0.33×0.07×0.50   绿皮书
//   yellowbook 0.654×0.134×1.000  → ×0.50 = 0.33×0.07×0.50   黄皮书

/** 每件家具的现实比例缩放（键与 models/furniture/<名>.glb 一致，与后端白名单一致） */
export const FURNITURE_SCALE: Record<string, number> = {
  bed: 1.55,
  desk: 1.25,
  chair: 1.1,
  cabinet: 1.3,
  computer: 0.85,
  record: 0.55,
  schoolbag: 0.42,
  tableLamp: 0.45,
  camera_my: 0.4,
  cup: 0.25,
  diary: 0.5,
  greenbook: 0.5,
  yellowbook: 0.5,
}

/** 模型名不在表里时的兜底缩放 */
export const FURNITURE_SCALE_DEFAULT = 1

/**
 * ★ 家具缩放已与用户手搭的场景对齐：main.scene 里那四件固定家具的 `_lscale` 全是 **2**
 *   （chair 是 (1, 1.5, 1)，它本来就矮，单独放大 Y）。
 *   后端下发的记忆家具必须用**同一个缩放**，否则房间自带的床和记忆生成的床大小不一。
 *
 *   为什么从原来那张"现实比例"表改成统一的 2：
 *   原表是按「房间缩放 4.5」反推的；场景改成缩放 10 之后，那套比例就不再匹配，
 *   而且它与用户已经摆好的场景对不上（床实际是 1.38 米长，符合单人的尺寸）。
 *
 *   尺寸（×2 之后，单位=米 ÷ 0.45）：床 0.96×1.38、书桌 1.07×0.56、书架 0.63×0.26。
 */
// 记忆家具（每条记忆生成的那一件）的基准缩放。
// 2 → 0.34：用户反馈「书太大了，其他模型也一样，缩小到原来的 6 分之 1」，
// 2 的六分之一就是 0.34。缩小后比例反而更接近真实（书 0.32 / 书架 1.38 ≈ 1:4.3）。
// ⚠ 场景里那四件固定家具是**预制体上的缩放**，代码改不到 —— 要一起缩小得在编辑器里
//   把 bed/cabinet/desk 的 _lscale 也从 2 改成 0.34（chair 改成 0.34/0.51/0.34）。

const USER_SCENE_SCALE: Record<string, number> = {
  bed: 0.34,
  desk: 0.34,
  cabinet: 0.34,

  // ★ 电脑 / 书包单独放大：用户反馈「电脑和书包应该比较大，其余原样」。
  //   0.34 时笔记本只有桌面的 1/7 宽，像个小玩具；放大后约为桌面宽度的 1/3，接近真实比例。
  
  computer: 0.8,
  record: 0.34,
  schoolbag: 0.6,
  tableLamp: 0.34,
  camera_my: 0.34,
  cup: 0.34,
  diary: 0.34,
  greenbook: 0.34,
  yellowbook: 0.34,
  chair: 0.51, // chair 走非等比缩放（Y 额外 ×1.5），见 furnitureScale3
}

/** 取某件家具的现实比例缩放 */
export function furnitureScale(name: string): number {
  const s = USER_SCENE_SCALE[name] ?? FURNITURE_SCALE[name]
  return typeof s === 'number' && s > 0 ? s : FURNITURE_SCALE_DEFAULT
}

/**
 * 取三轴缩放。椅子在用户场景里是 `_lscale = (1, 1.5, 1)`（只加高、横向保持原宽），
 * 统一等比缩放会让椅子明显偏胖，这里按用户搭的样子原样复刻。
 */
export function furnitureScale3(name: string): [number, number, number] {
  if (name === 'chair') return [0.34, 0.51, 0.34]
  const s = furnitureScale(name)
  return [s, s, s]
}
